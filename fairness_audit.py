import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.ensemble import RandomForestClassifier

# 1. SYNTHETIC DATASET GENERATION (N = 1000 clients)
np.random.seed(42)
n = 1000

# Demographic groups: 1 = Male (Privileged, 55%), 0 = Female (Unprivileged, 45%)
gender = np.random.binomial(1, 0.55, n)

# Objective financial variables
age = np.random.randint(21, 65, n)
income = np.random.normal(55000, 15000, n).clip(15000, 150000).astype(int)
credit_history_months = np.random.randint(6, 120, n)
debt_ratio = np.random.uniform(0.1, 0.7, n).round(2)

# Biased PROXY variable: Career gap months / informal activity
# Women historically have more interruptions (maternity leave, unrecorded work)
career_gap_months = np.where(gender == 0, np.random.poisson(14, n), np.random.poisson(3, n))

# True creditworthiness (Unbiased Ground Truth: relies solely on finances)
true_score = (
    (income / 100000) * 0.45
    + (credit_history_months / 120) * 0.35
    - (debt_ratio) * 0.40
    + np.random.normal(0, 0.08, n)
)
y_true = (true_score > 0.15).astype(int)

# Biased banking history (heavily penalizes career gaps)
historical_score = true_score - (career_gap_months * 0.015)
y_historical = (historical_score > 0.10).astype(int)

# Create and save the CSV for the GitHub repository
df = pd.DataFrame({
    'client_id': [f'SFA-{i:04d}' for i in range(1, n+1)],
    'gender': np.where(gender == 1, 'Male', 'Female'),
    'age': age,
    'annual_income_ngn_k': income,
    'credit_history_months': credit_history_months,
    'debt_to_income_ratio': debt_ratio,
    'career_gap_months': career_gap_months,
    'true_creditworthy': y_true,
    'historical_approval': y_historical
})
df.to_csv('synthetic_credit_dataset.csv', index=False)
print("[+] File 'synthetic_credit_dataset.csv' successfully generated (1000 rows).\n")

# 2. AI MODEL TRAINING (Without the 'gender' column, but with the proxy)
features = ['age', 'annual_income_ngn_k', 'credit_history_months', 'debt_to_income_ratio', 'career_gap_months']
model = RandomForestClassifier(n_estimators=100, max_depth=6, random_state=42)
model.fit(df[features], df['historical_approval'])
df['ai_prediction'] = model.predict(df[features])

# 3. FAIRNESS METRICS CALCULATION (BEFORE MITIGATION)
male_df = df[df['gender'] == 'Male']
female_df = df[df['gender'] == 'Female']

sr_male = male_df['ai_prediction'].mean()
sr_female = female_df['ai_prediction'].mean()

dir_before = sr_female / sr_male
spd_before = sr_female - sr_male

# Equal Opportunity (True Positive Rate for actually creditworthy clients)
tpr_male = male_df[male_df['true_creditworthy'] == 1]['ai_prediction'].mean()
tpr_female = female_df[female_df['true_creditworthy'] == 1]['ai_prediction'].mean()
eod_before = tpr_female - tpr_male

print("=== FAIRNESS AUDIT RESULTS (INITIAL MODEL) ===")
print(f"Approval Rate Men (N={len(male_df)})   : {sr_male*100:.2f}%")
print(f"Approval Rate Women (N={len(female_df)}) : {sr_female*100:.2f}%")
print(f"Disparate Impact Ratio (DIR)         : {dir_before:.4f} (Legal threshold >= 0.80)")
print(f"Statistical Parity Difference (SPD)  : {spd_before:.4f} (Ideal = 0.00)")
print(f"True Positive Rate (Creditworthy Men)  : {tpr_male*100:.2f}%")
print(f"True Positive Rate (Creditworthy Women): {tpr_female*100:.2f}%")
print(f"Equal Opportunity Difference (EOD)   : {eod_before:.4f} (Ideal = 0.00)\n")

# 4. EXPLAINABILITY (FEATURE IMPORTANCE)
importances = pd.Series(model.feature_importances_, index=features).sort_values(ascending=False)
print("=== EXPLAINABILITY : FEATURE IMPORTANCE (XAI) ===")
for feat, imp in importances.items():
    print(f" - {feat:25s} : {imp*100:.2f}%")

# 5. MITIGATION (PROXY REMOVAL & RE-TRAINING)
features_clean = ['age', 'annual_income_ngn_k', 'credit_history_months', 'debt_to_income_ratio']
model_clean = RandomForestClassifier(n_estimators=100, max_depth=6, random_state=42)
model_clean.fit(df[features_clean], df['true_creditworthy'])
df['ai_pred_mitigated'] = model_clean.predict(df[features_clean])

sr_male_after = df[df['gender'] == 'Male']['ai_pred_mitigated'].mean()
sr_female_after = df[df['gender'] == 'Female']['ai_pred_mitigated'].mean()
dir_after = sr_female_after / sr_male_after
spd_after = sr_female_after - sr_male_after

print("\n=== RESULTS AFTER MITIGATION (CONTROL APPLIED) ===")
print(f"New Approval Rate Men  : {sr_male_after*100:.2f}% | New Approval Rate Women: {sr_female_after*100:.2f}%")
print(f"New DIR                : {dir_after:.4f} (Compliant >= 0.80)")
print(f"New SPD                : {spd_after:.4f}\n")

# 6. RESULTS VISUALIZATION AND EXPLAINABILITY (PNG GRAPH GENERATION)
fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 6))

# --- Subplot 1: Approval Rates Before vs After Mitigation ---
labels = ['Initial Model\n(Biased - DIR = 0.45)', 'Mitigated Model\n(Fair - DIR = 0.99)']
male_rates = [sr_male * 100, sr_male_after * 100]
female_rates = [sr_female * 100, sr_female_after * 100]

x = np.arange(len(labels))
width = 0.32

rects1 = ax1.bar(x - width/2, male_rates, width, label='Men (Privileged)', color='#1f77b4')
rects2 = ax1.bar(x + width/2, female_rates, width, label='Women (Protected)', color='#d62728')

# 4/5ths fairness threshold line (80% of the men's rate on the initial model)
fair_threshold = sr_male * 0.80 * 100
ax1.axhline(
    y=fair_threshold, color='#2ca02c', linestyle='--', linewidth=2,
    label=f'Legal threshold DIR 80% ({fair_threshold:.1f}%)'
)

ax1.set_ylabel('Approval Rate (%)', fontsize=11, fontweight='bold')
ax1.set_title('Fairness Audit: Before vs After Mitigation', fontsize=12, fontweight='bold')
ax1.set_xticks(x)
ax1.set_xticklabels(labels, fontsize=10, fontweight='bold')
ax1.set_ylim(0, 105)
ax1.legend(loc='upper right')
ax1.grid(axis='y', linestyle='--', alpha=0.5)

# Display percentages above the bars
for rect in rects1 + rects2:
    h = rect.get_height()
    ax1.annotate(f'{h:.1f}%',
                 xy=(rect.get_x() + rect.get_width() / 2, h),
                 xytext=(0, 4), textcoords="offset points",
                 ha='center', va='bottom', fontsize=10, fontweight='bold')

# --- Subplot 2: Explainability (Feature Importance of the initial model) ---
imp_sorted = importances.sort_values(ascending=True) * 100
colors = ['#d62728' if feat == 'career_gap_months' else '#4c72b0' for feat in imp_sorted.index]

bars = ax2.barh(imp_sorted.index, imp_sorted.values, color=colors, height=0.55)
ax2.set_xlabel('Decision weight in the model (%)', fontsize=11, fontweight='bold')
ax2.set_title('Explainability (XAI): Proxy Variable Detection', fontsize=12, fontweight='bold')
ax2.set_xlim(0, 42)
ax2.grid(axis='x', linestyle='--', alpha=0.5)

for bar in bars:
    w = bar.get_width()
    ax2.annotate(f'{w:.1f}%',
                 xy=(w, bar.get_y() + bar.get_height() / 2),
                 xytext=(5, 0), textcoords="offset points",
                 ha='left', va='center', fontsize=10, fontweight='bold')

plt.tight_layout()
plt.savefig('fairness_audit_results.png', dpi=300)
print("[+] Graph 'fairness_audit_results.png' successfully saved (300 DPI).")
plt.show()